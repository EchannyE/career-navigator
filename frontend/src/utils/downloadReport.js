export const downloadReport = (content = "", filename) => {
  if (!content || !String(content).trim()) {
    console.warn("No report content available for download.");
    return;
  }

  const safeTimestamp = new Date()
    .toISOString()
    .slice(0, 19)
    .replace(/[:T]/g, "-");

  const name = filename || `career-coach-report-${safeTimestamp}.html`;

  const escapedContent = String(content)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");

  const html = `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>Career Coach Navigator Report</title>
  <style>
    body {
      font-family: Arial, sans-serif;
      background: #f8fafc;
      color: #0f172a;
      padding: 40px;
      line-height: 1.7;
    }

    .container {
      max-width: 850px;
      margin: auto;
      background: #ffffff;
      padding: 40px;
      border-radius: 18px;
      box-shadow: 0 20px 50px rgba(15, 23, 42, 0.08);
      border: 1px solid #e2e8f0;
    }

    .header {
      border-bottom: 3px solid #2563eb;
      padding-bottom: 20px;
      margin-bottom: 30px;
    }

    .badge {
      display: inline-block;
      background: #dbeafe;
      color: #1d4ed8;
      padding: 6px 12px;
      border-radius: 999px;
      font-size: 12px;
      font-weight: bold;
      margin-bottom: 12px;
    }

    h1 {
      margin: 0;
      font-size: 30px;
      color: #0f172a;
    }

    .subtitle {
      color: #64748b;
      margin-top: 8px;
    }

    pre {
      white-space: pre-wrap;
      word-wrap: break-word;
      font-family: Arial, sans-serif;
      font-size: 15px;
    }

    .footer {
      margin-top: 35px;
      padding-top: 20px;
      border-top: 1px solid #e2e8f0;
      font-size: 12px;
      color: #64748b;
      text-align: center;
    }

    @media print {
      body {
        background: white;
        padding: 0;
      }

      .container {
        box-shadow: none;
        border: none;
      }
    }
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <div class="badge">Career Coach Navigator</div>
      <h1>AI Career Fit Report</h1>
      <p class="subtitle">Personalized resume-to-job gap analysis and action plan</p>
    </div>

    <pre>${escapedContent}</pre>

    <div class="footer">
      Generated by Career Coach Navigator
    </div>
  </div>
</body>
</html>
`;

  const blob = new Blob([html], {
    type: "text/html;charset=utf-8",
  });

  const url = URL.createObjectURL(blob);

  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = name;
  anchor.style.display = "none";

  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);

  setTimeout(() => {
    URL.revokeObjectURL(url);
  }, 100);
};
